#!/usr/bin/env bash
# Generates prometheus/targets/transactions.yml — the scrape target for the
# transaction-log poller (txn-poller), labelled with TXN_ENV.
#
# The poller is only run when COMPOSE_PROFILES includes "transactions". Otherwise
# the file is left with no targets, so nothing is scraped and no false "down"
# alert fires.
#
# Called automatically by scripts/deploy.sh (which loads .env). Safe to run on
# its own after:  set -a; . ./.env; set +a
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="prometheus/targets/transactions.yml"

case ",${COMPOSE_PROFILES:-}," in
  *,transactions,*) ;;
  *)
    echo "# GENERATED — transaction logs are OFF (COMPOSE_PROFILES has no 'transactions')." > "$OUT"
    echo "Transaction logs disabled (COMPOSE_PROFILES has no 'transactions') — no poller scraped."
    exit 0 ;;
esac

case "${TXN_API_URL:-}" in
  http://*|https://*) ;;
  *)
    echo "ERROR: COMPOSE_PROFILES includes 'transactions' but TXN_API_URL in .env is not" >&2
    echo "       an http(s) address. Set it, or take 'transactions' out of COMPOSE_PROFILES." >&2
    exit 1 ;;
esac
case "${TXN_API_URL}${TXN_API_KEY:-}" in
  *example.com*|*replace-with-api-key*)
    echo "WARNING: TXN_API_URL / TXN_API_KEY still hold the example values from .env.example." ;;
esac

{
  echo "# GENERATED by scripts/render-transactions-config.sh — do not edit by hand."
  echo "# Set TXN_* in .env, then run: bash scripts/deploy.sh"
  echo "- targets: ['txn-poller:9488']"
  echo "  labels:"
  echo "    instance: transactions-feed"
  if [ -n "${TXN_ENV:-}" ]; then
    echo "    env: '$(printf '%s' "$TXN_ENV" | sed "s/'/''/g")'"
  fi
} > "$OUT"
echo "Rendered $OUT (transaction feed${TXN_ENV:+, env=${TXN_ENV}})"
